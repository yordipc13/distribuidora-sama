function updateHeroAutoplayButton() {
	const button = document.querySelector("[data-hero-toggle]");
	if (!button) return;
	const isPaused = heroAutoplayPaused || reducedMotionPreference.matches;
	const label = reducedMotionPreference.matches ? t("autoplayDisabledByPreference") : t(isPaused ? "resumeCarousel" : "pauseCarousel");
	button.textContent = isPaused ? "▶" : "Ⅱ";
	button.disabled = reducedMotionPreference.matches;
	button.setAttribute("aria-label", label);
	button.title = label;
	button.setAttribute("aria-pressed", String(isPaused));
}
function syncHeroAutoplay() {
	pauseHeroAutoplay();
	updateHeroAutoplayButton();
	const carousel = document.querySelector(".hero-carousel");
	if (!carousel || document.hidden || heroAutoplayPaused || reducedMotionPreference.matches || carousel.matches(":hover") || carousel.contains(document.activeElement)) return;
	carousel.classList.remove("is-paused");
	resetHeroProgress();
	heroAutoplayTimer = window.setInterval(() => setHeroSlide(activeHeroSlide + 1), heroAutoplayDelay);
}
