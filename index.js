function setHeroSlide(index) {
	activeHeroSlide = (index + heroCategories.length) % heroCategories.length;
	document.querySelectorAll(".hero-slide").forEach((slide, slideIndex) => {
		const isActive = slideIndex === activeHeroSlide;
		slide.hidden = !isActive;
		slide.setAttribute("aria-hidden", String(!isActive));
	});
	document.querySelectorAll("[data-hero-indicator]").forEach(button => {
		const isActive = Number(button.dataset.heroIndicator) === activeHeroSlide;
		button.classList.toggle("active", isActive);
		button.setAttribute("aria-pressed", String(isActive));
	});
	const counter = document.querySelector("[data-hero-count]");
	if (counter) counter.textContent = `${activeHeroSlide + 1} / ${heroCategories.length}`;
}
