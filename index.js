	if (carousel) {
		carousel.addEventListener("pointerenter", pauseHeroAutoplay);
		carousel.addEventListener("pointerleave", syncHeroAutoplay);
		carousel.addEventListener("focusin", pauseHeroAutoplay);
		carousel.addEventListener("focusout", event => { if (!carousel.contains(event.relatedTarget)) syncHeroAutoplay(); });
		carousel.addEventListener("pointerdown", event => { if (event.pointerType === "touch") heroSwipeStartX = event.clientX; });
		carousel.addEventListener("pointerup", event => {
			if (heroSwipeStartX === null) return;
			const distance = event.clientX - heroSwipeStartX;
			heroSwipeStartX = null;
			if (Math.abs(distance) > 48) {
				setHeroSlide(activeHeroSlide + (distance < 0 ? 1 : -1));
				syncHeroAutoplay();
			}
		});
		carousel.addEventListener("pointercancel", () => { heroSwipeStartX = null; });
	}
